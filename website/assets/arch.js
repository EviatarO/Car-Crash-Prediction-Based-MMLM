/* ================================================================= arch.js
   buildArch(hostEl, opts) - the hand-drawn architecture diagram, shared by the
   landing page (default configuration) and the experiments page (recoloured
   per arm to show what that arm actually trains).

   Hand-drawn (not the PNG) so it stays crisp at any zoom and matches the site
   palette. Redrawn from reports/figures/arch_L3_training_a1fail_2026-08-29.png
   (which itself is generated by make_arch_figures_2026-08-22.py::fig_L3 - the
   vector-shape labels below are copied verbatim from that script, not guessed):
   crash path (always active) vs the train-only semantic branch (discarded at
   inference), sharing the same frozen V-JEPA2 trunk + trainable LoRA.

   Deliberate differences from the reference PNG (both per explicit review
   feedback, 2026-09-01):
   - No "patch grid" box. In the reference PNG there never was one either - the
     trunk's own output tensor (1,2560,1024) is consumed twice, once pooled by
     the temporal processor (crash path) and once raw by the Predictor
     (semantic path). Drawing it as its own box implied a module that does not
     exist; both consumers now branch directly off V-JEPA2 ViT-L.
   - Teacher caption sits LEFT of SigLIP with a left-to-right arrow (the
     reference PNG stacks them vertically instead) - matches the actual data
     flow (caption text -> encoder) more directly.
   - No boxed "L" combination node (its two incoming arrows kept crossing the
     dashed train-only boundary at an angle that made the diagram read as
     "L is a fifth, separate module"). Replaced with a single bold equation
     line under the diagram - still inside the SVG so it stays part of the
     figure if copied out, but it is text, not a computation node.

   opts (all optional; omitting ALL of them reproduces the landing page's
   original diagram byte-for-byte, which is asserted by the verification step):
     semantic  bool   draw the train-only semantic branch      (default true)
     loss      bool   draw the L_crash box                     (default true)
     state     obj    per-module override, keys: trunk lora tproc clsf pred
                      siglip; values "frozen" | "train" | "absent"
     note      str    one-line caption under the diagram (e.g. weight init)
   ================================================================= */
(function (global) {
  const NS = "http://www.w3.org/2000/svg";
  const CYAN = "#00BFFF", GREEN = "#00E676", AMBER = "#FFA726", MUTED = "#A0B4CC",
        WHITE = "#FFFFFF", PANEL = "#1C2340", PANEL_DK = "#161d36";

  function box(x, y, w, h, {fill=PANEL, stroke=CYAN, dash=null, rx=8} = {}){
    const r = document.createElementNS(NS, "rect");
    r.setAttribute("x", x); r.setAttribute("y", y);
    r.setAttribute("width", w); r.setAttribute("height", h);
    r.setAttribute("rx", rx); r.setAttribute("fill", fill);
    r.setAttribute("stroke", stroke); r.setAttribute("stroke-width", 1.6);
    if (dash) r.setAttribute("stroke-dasharray", dash);
    return r;
  }
  function label(x, y, text, {size=13.2, color=WHITE, anchor="middle", weight=600, mono=true, italic=false} = {}){
    const t = document.createElementNS(NS, "text");
    t.setAttribute("x", x); t.setAttribute("y", y);
    t.setAttribute("text-anchor", anchor);
    t.setAttribute("font-size", size);
    t.setAttribute("font-weight", weight);
    t.setAttribute("fill", color);
    if (italic) t.setAttribute("font-style", "italic");
    if (mono) t.setAttribute("font-family", "Consolas,'Cascadia Mono',ui-monospace,monospace");
    t.textContent = text;
    return t;
  }
  function block(x, y, w, h, title, sub, opts){
    const g = document.createElementNS(NS, "g");
    g.appendChild(box(x, y, w, h, opts));
    g.appendChild(label(x + w/2, y + h/2 - (sub ? 6 : -4), title, {size:13.8}));
    if (sub) g.appendChild(label(x + w/2, y + h/2 + 15, sub, {size:10.5, color:MUTED, weight:400}));
    return g;
  }
  function arrow(x1, y1, x2, y2, color=MUTED){
    const l = document.createElementNS(NS, "line");
    l.setAttribute("x1", x1); l.setAttribute("y1", y1);
    l.setAttribute("x2", x2); l.setAttribute("y2", y2);
    l.setAttribute("stroke", color); l.setAttribute("stroke-width", 1.6);
    // arrowhead marker must match the line's own color, or a green-tinted arrow
    // (LoRA->trunk, the trunk->Predictor elbow) would still end in a grey head.
    l.setAttribute("marker-end", color === GREEN ? "url(#arrowhead-g)" : "url(#arrowhead)");
    return l;
  }
  /* elbow: vertical run then horizontal run, one shape/tensor-size label near the
     horizontal leg - used for the two branches off the trunk's shared output. */
  function elbow(x1, y1, xTurn, y2, color=MUTED){
    const g = document.createElementNS(NS, "g");
    const v = document.createElementNS(NS, "line");
    v.setAttribute("x1", x1); v.setAttribute("y1", y1);
    v.setAttribute("x2", x1); v.setAttribute("y2", y2);
    v.setAttribute("stroke", color); v.setAttribute("stroke-width", 1.6);
    g.appendChild(v);
    g.appendChild(arrow(x1, y2, xTurn, y2, color));
    return g;
  }
  function shapeLabel(cx, y, text, color=MUTED){
    return label(cx, y, text, {size:9.9, color, weight:400, italic:true});
  }

  /* Default appearance of every module. `state` decides the colour; the sub-caption
     is spelled out per module because two of them read better with extra context
     ("frozen trunk", "8 queries · trainable") than a bare "frozen"/"trainable".
     An override in opts.state replaces BOTH the colour and the sub-caption, so a
     recoloured module never keeps a caption contradicting its new colour. */
  const DEFAULTS = {
    trunk:  {sub: "frozen trunk",           state: "frozen"},
    lora:   {sub: "trainable",              state: "train"},
    tproc:  {sub: "frozen",                 state: "frozen"},
    clsf:   {sub: "frozen",                 state: "frozen"},
    pred:   {sub: "8 queries · trainable",  state: "train"},
    siglip: {sub: "frozen",                 state: "frozen"},
  };

  function resolve(key, override){
    const d = DEFAULTS[key];
    if (!override || !override[key] || override[key] === d.state){
      return {state: d.state, sub: d.sub};
    }
    const st = override[key];
    return {state: st, sub: st === "train" ? "trainable" : "frozen"};
  }

  // Green fill only for trainable modules; frozen ones keep the flat panel fill.
  function styleOf(r){
    return r.state === "train" ? {stroke: GREEN, fill: "#16321f"} : {stroke: CYAN};
  }

  global.buildArch = function buildArch(host, opts){
    opts = opts || {};
    const semantic = opts.semantic !== false;
    const showLoss = opts.loss !== false;
    const st = opts.state || null;

    const mods = {};
    for (const k of Object.keys(DEFAULTS)) mods[k] = resolve(k, st);
    const showLora = mods.lora.state !== "absent";

    // The canvas only needs the full 500px when the semantic branch is drawn; a
    // crash-only arm would otherwise render with 300px of empty space under it.
    const W = 1000, H = semantic ? 500 : (opts.note ? 215 : 190);
    const svg = document.createElementNS(NS, "svg");
    svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
    svg.setAttribute("width", W);

    const defs = document.createElementNS(NS, "defs");
    defs.innerHTML = `<marker id="arrowhead" markerWidth="8" markerHeight="8" refX="6" refY="3"
      orient="auto"><path d="M0,0 L6,3 L0,6 z" fill="${MUTED}"/></marker>
      <marker id="arrowhead-g" markerWidth="8" markerHeight="8" refX="6" refY="3"
      orient="auto"><path d="M0,0 L6,3 L0,6 z" fill="${GREEN}"/></marker>`;
    svg.appendChild(defs);

    /* train-only region - covers the semantic branch only (predictor/L_sem/SigLIP/
       caption), NOT the crash path and NOT the equation line, matching what is
       actually discarded at inference. */
    if (semantic){
      const region = box(340, 195, 630, 175, {fill:PANEL_DK, stroke:AMBER, dash:"6 5", rx:12});
      svg.appendChild(region);
      svg.appendChild(label(950, 216, "train-only · discarded at inference",
        {size:10.5, color:AMBER, anchor:"end", weight:600}));
    }

    /* ---- crash path (top row, always active) ---- */
    const cy = 60, ch = 60, ccy = cy + ch / 2;
    const frames = block(20, cy, 110, ch, "16 frames", "1280×720", {stroke:MUTED});
    const trunk  = block(170, cy, 150, ch, "V-JEPA2 ViT-L", mods.trunk.sub, styleOf(mods.trunk));
    const tproc  = block(360, cy, 140, ch, "temporal processor", mods.tproc.sub, styleOf(mods.tproc));
    const clsf   = block(535, cy, 110, ch, "classifier", mods.clsf.sub, styleOf(mods.clsf));
    const pcoll  = block(680, cy, 100, ch, "P(collision)", "softmax(z)", {stroke:MUTED});
    const row = [frames, trunk];
    if (showLora){
      row.push(block(170, cy + ch + 15, 150, 34, "LoRA r=16", mods.lora.sub, styleOf(mods.lora)));
    }
    row.push(tproc, clsf, pcoll);
    if (showLoss){
      row.push(block(815, cy, 90, ch, "L_crash", "CE(z, y)", {stroke:AMBER, fill:"#3a2410"}));
    }
    row.forEach(b => svg.appendChild(b));

    // LoRA -> trunk: the connection that was previously missing entirely.
    if (showLora) svg.appendChild(arrow(245, cy + ch + 15, 245, cy + ch, GREEN));

    // Shape labels sit ABOVE the whole row (cy - 10, clear of every box's top edge
    // at y=cy), not just above the arrow's own midline (ccy) - the gaps between
    // adjacent boxes are narrower than most of these label strings, so a label
    // centered in the gap at arrow height spills sideways into the neighboring
    // box titles. Floating them in the open margin above the row avoids that
    // regardless of label width.
    svg.appendChild(arrow(130, ccy, 170, ccy));
    svg.appendChild(shapeLabel(150, cy - 10, "(1, 16, 3, 256, 320)"));
    svg.appendChild(arrow(320, ccy, 360, ccy));
    svg.appendChild(shapeLabel(340, cy - 10, "(1, 2560, 1024)"));
    svg.appendChild(arrow(500, ccy, 535, ccy));
    svg.appendChild(shapeLabel(517, cy - 10, "(1, 1024)"));
    svg.appendChild(arrow(645, ccy, 680, ccy));
    svg.appendChild(shapeLabel(662, cy - 10, "(1, 2) logits"));
    if (showLoss) svg.appendChild(arrow(780, ccy, 815, ccy));

    /* ---- semantic branch (train-only region) ---- */
    if (semantic){
      const sy = 240, sh = 58, scy = sy + sh / 2;
      const pred  = block(360, sy, 140, sh, "Predictor", mods.pred.sub, styleOf(mods.pred));
      svg.appendChild(shapeLabel(430, sy + sh + 14, "(1, 8, 768) → mean over queries"));
      const lsem  = block(560, sy, 100, sh, "L_sem", "InfoNCE", {stroke:AMBER, fill:"#3a2410"});
      const cy3 = 335, ch3 = 58, ccy3 = cy3 + ch3 / 2;
      const cap    = block(400, cy3, 150, ch3, "teacher caption", "one sentence / clip", {stroke:MUTED});
      const siglip = block(600, cy3, 150, ch3, "SigLIP text enc.", mods.siglip.sub, styleOf(mods.siglip));
      [pred, lsem, cap, siglip].forEach(b => svg.appendChild(b));

      // trunk -> Predictor: same source point the crash path branches from (320,ccy),
      // down then right into Predictor's left edge - the SAME tensor as the crash
      // path's own (1,2560,1024), not a separately-computed feature map.
      const elb = elbow(320, ccy, 360, scy, GREEN);
      svg.appendChild(elb);
      svg.appendChild(shapeLabel(340, sy - 10, "(1, 2560, 1024)", GREEN));

      svg.appendChild(arrow(500, scy, 560, scy));
      svg.appendChild(shapeLabel(530, scy - 12, "(1, 768)"));
      // caption -> SigLIP (left-to-right, per review feedback)
      svg.appendChild(arrow(550, ccy3, 600, ccy3));
      // SigLIP -> L_sem (up into the loss, arriving from below-right)
      svg.appendChild(arrow(675, cy3, 675, sy + sh, CYAN));
      svg.appendChild(shapeLabel(700, cy3 - 8, "(1, 768)"));

      /* ---- loss equation: bold text, not a box - the two branches above already
         show where each term comes from; this line just states how they combine. */
      svg.appendChild(label(W / 2, 465, "L  =  L_crash  +  λ · L_sem",
        {size:19, weight:700, color:AMBER}));
    }

    if (opts.note){
      svg.appendChild(label(W / 2, H - 12, opts.note,
        {size:11.5, color:MUTED, weight:400, italic:true}));
    }

    host.appendChild(svg);
    return svg;
  };
})(window);
